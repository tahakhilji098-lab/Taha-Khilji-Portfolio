export interface OptimizedImage {
  /** Original file basename without extension. */
  key: string;
  /** Intrinsic dimensions of the source image. */
  width: number;
  height: number;
  /** Largest generated variant, used for hover preloading. */
  largestUrl: string;
  avifSrcSet: string;
  webpSrcSet: string;
}

const widthOf = (fileName: string): number => {
  const match = fileName.match(/-(\d+)\.(avif|webp)$/);
  return match ? Number(match[1]) : 0;
};

const buildSrcSet = (urls: Record<string, string>): string =>
  Object.entries(urls)
    .sort(([a], [b]) => widthOf(a) - widthOf(b))
    .map(([fileName, url]) => `${url} ${widthOf(fileName)}w`)
    .join(', ');

const keyOf = (fileName: string): string =>
  fileName.replace(/-\d+\.(avif|webp)$/, '');

const collect = (urls: Record<string, string>) => {
  const grouped = new Map<string, Record<string, string>>();
  for (const [fileName, url] of Object.entries(urls)) {
    const key = keyOf(fileName);
    const bucket = grouped.get(key) ?? {};
    bucket[fileName] = url;
    grouped.set(key, bucket);
  }
  return grouped;
};

const avifGrouped = collect(AVIF_URLS);
const webpGrouped = collect(WEBP_URLS);

export const optimizedImages: Record<string, OptimizedImage> = {};

for (const key of new Set([...avifGrouped.keys(), ...webpGrouped.keys()])) {
  const avif = avifGrouped.get(key);
  const webp = webpGrouped.get(key);
  if (!avif || !webp) continue;

  const dimensions = SOURCE_DIMENSIONS[key];
  if (!dimensions) continue;

  const largestEntry = Object.entries(avif).sort(
    ([a], [b]) => widthOf(b) - widthOf(a),
  )[0];

  optimizedImages[key] = {
    key,
    width: dimensions.width,
    height: dimensions.height,
    largestUrl: largestEntry[1],
    avifSrcSet: buildSrcSet(avif),
    webpSrcSet: buildSrcSet(webp),
  };
}

/**
 * Resolves a <img src> value (public path, imported Vite URL, remote URL)
 * to the optimized-variant record. Hashed Vite URLs match through their
 * original stem prefix, e.g. '/assets/brand_mockup_.....-xxxx.jpg'.
 */
export function getOptimizedImage(src: string): OptimizedImage | undefined {
  const basename = src.split('?')[0].split('/').pop() ?? '';
  const stem = basename.replace(/\.(png|jpe?g|webp|avif)$/i, '').toLowerCase();
  if (!stem) return undefined;
  const direct = optimizedImages[stem];
  if (direct) return direct;
  const byPrefix = Object.keys(optimizedImages).find(
    (key) => stem.length > key.length && stem.startsWith(`${key}-`),
  );
  return byPrefix ? optimizedImages[byPrefix] : undefined;
}