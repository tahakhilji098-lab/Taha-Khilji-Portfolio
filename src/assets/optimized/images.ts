/*
  Runtime manifest for the optimized image variants generated by
  scripts/optimize-images.mjs into this directory.

  Variant files are discovered with import.meta.glob (URL strings only, so
  nothing is bundled into JavaScript). Lookup is keyed by the original file
  basename without extension, e.g. 'work-01-aureli-brand-identity'.

  Fallback <img> sources keep pointing at the untouched originals.
*/

const AVIF_URLS = import.meta.glob('./*.avif', {
  eager: true,
  import: 'default',
  query: '?url',
}) as Record<string, string>;

const WEBP_URLS = import.meta.glob('./*.webp', {
  eager: true,
  import: 'default',
  query: '?url',
}) as Record<string, string>;

